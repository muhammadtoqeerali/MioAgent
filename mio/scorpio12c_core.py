class CodingStop(RuntimeError):
    """No operation performed outside the explicit policy."""


def _id(raw: str) -> str:
    if not isinstance(raw, str) or not ID.fullmatch(raw):
        raise CodingStop("Invalid coding job identifier")
    return raw


def _store(root: Path) -> Path:
    root = Path(root)
    expected_parent = Path(f"/var/tmp/mioagent-native-{os.getuid()}")
    if not root.is_absolute() or root.is_symlink() or root.parent != expected_parent:
        raise CodingStop("Coding store must be the owner-private native runtime child")
    for item in (expected_parent, root):
        if item.is_symlink():
            raise CodingStop("Symlink storage is forbidden")
        if not item.exists():
            if item == expected_parent:
                raise CodingStop("Native runtime not initialized")
            item.mkdir(mode=0o700)
        info = item.stat()
        if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) & 0o077:
            raise CodingStop("Private runtime ownership or mode invalid")
    return root


@contextmanager
def db(root: Path = STORE):
    location = _store(root)
    database = location / "jobs.db"
    if database.is_symlink():
        raise CodingStop("Symlink coding database forbidden")
    connection = sqlite3.connect(database, timeout=8)
    try:
        info = database.stat()
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid():
            raise CodingStop("Coding database owner or type invalid")
        database.chmod(0o600)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA busy_timeout=8000")
        connection.execute("PRAGMA foreign_keys=ON")
        connection.executescript("""
            CREATE TABLE IF NOT EXISTS jobs (
                id TEXT PRIMARY KEY, case_name TEXT NOT NULL, state TEXT NOT NULL,
                created INTEGER NOT NULL, updated INTEGER NOT NULL,
                result TEXT, error TEXT
            );
            CREATE TABLE IF NOT EXISTS events (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                job TEXT NOT NULL REFERENCES jobs(id), phase TEXT NOT NULL,
                detail TEXT NOT NULL, created INTEGER NOT NULL
            );
        """)
        yield connection
        connection.commit()
    finally:
        connection.close()


def _event(conn: sqlite3.Connection, job: str, phase: str, detail: str) -> None:
    if conn.execute("SELECT COUNT(*) FROM events WHERE job=?", (job,)).fetchone()[0] >= MAX_EVENTS:
        raise CodingStop("Event budget exhausted")
    conn.execute("INSERT INTO events(job,phase,detail,created) VALUES (?,?,?,?)",
                 (job, phase, detail[:350], int(time.time())))


def _read(conn: sqlite3.Connection, job_id: str) -> dict:
    row = conn.execute("SELECT * FROM jobs WHERE id=?", (_id(job_id),)).fetchone()
    if row is None:
        raise CodingStop("Coding job does not exist")
    result = dict(row)
    result["result"] = json.loads(result["result"]) if result["result"] else None
    result["events"] = [dict(x) for x in conn.execute(
        "SELECT phase,detail,created FROM events WHERE job=? ORDER BY id LIMIT ?",
        (job_id, MAX_EVENTS))]
    return result


def create_job(case_name: str, *, root: Path = STORE) -> dict:
    if not isinstance(case_name, str) or case_name not in CASES:
        raise CodingStop("Only platform-provided offline demonstration cases are allowed")
    job_id = uuid.uuid4().hex
    now = int(time.time())
    with db(root) as conn:
        conn.execute("BEGIN IMMEDIATE")
        if conn.execute("SELECT COUNT(*) FROM jobs").fetchone()[0] >= MAX_JOBS:
            raise CodingStop("Offline coding job limit reached")
        conn.execute("INSERT INTO jobs VALUES (?,?,?,?,?,?,?)",
                     (job_id, case_name, "draft", now, now, None, None))
        _event(conn, job_id, "created", "Approved synthetic rehearsal only; no model access")
        return _read(conn, job_id)


def list_jobs(*, root: Path = STORE) -> dict:
    with db(root) as conn:
        rows = conn.execute(
            "SELECT id,case_name,state,created,updated FROM jobs ORDER BY created DESC,id DESC LIMIT 60"
        ).fetchall()
    return {"jobs": [dict(row) for row in rows]}


def read_job(job_id: str, *, root: Path = STORE) -> dict:
    with db(root) as conn:
        return _read(conn, job_id)


def cancel_job(job_id: str, *, root: Path = STORE) -> dict:
    with db(root) as conn:
        conn.execute("BEGIN IMMEDIATE")
        job = _read(conn, job_id)
        if job["state"] == "draft":
            conn.execute("UPDATE jobs SET state='canceled',updated=? WHERE id=?",
                         (int(time.time()), job_id))
            _event(conn, job_id, "canceled", "Owner canceled before execution")
        elif job["state"] == "running":
            # Cooperative cancellation only; no process kill.
            conn.execute("UPDATE jobs SET state='cancel_requested',updated=? WHERE id=?",
                         (int(time.time()), job_id))
            _event(conn, job_id, "cancel_requested", "Owner requested cooperative stop")
        else:
            raise CodingStop("Only a draft or running rehearsal can be canceled")
        return _read(conn, job_id)


def _cancelled(root: Path, job_id: str) -> bool:
    with db(root) as conn:
        return _read(conn, job_id)["state"] == "cancel_requested"


def _note(root: Path, job_id: str, phase: str, detail: str) -> None:
    with db(root) as conn:
        _event(conn, job_id, phase, detail)


def execute_job(job_id: str, *, root: Path = STORE) -> dict:
    """Synchronous and bounded. Only deterministic synthetic source is ever staged."""
    with db(root) as conn:
        conn.execute("BEGIN IMMEDIATE")
        job = _read(conn, job_id)
        if job["state"] != "draft":
            raise CodingStop("Only an unstarted draft may run once")
        conn.execute("UPDATE jobs SET state='running',updated=? WHERE id=?",
                     (int(time.time()), job_id))
        _event(conn, job_id, "started", "Fixed reference script; NOT LLM autonomy")
    fixture = CASES[job["case_name"]]
    result = None
    final_state = "failed"
    failure = None
    try:
        with tempfile.TemporaryDirectory(prefix="s12c-job-", dir=_store(root)) as td:
            scratch = Path(td)
            scratch.chmod(0o700)
            project = scratch / "demo-repository"
            project.mkdir(mode=0o700)
            (project / "engine.py").write_text(fixture["source"], encoding="utf-8")
            (project / "test_engine.py").write_text(fixture["test"], encoding="utf-8")
            goal = RepoGoal.parse({
                "repository": str(project), "task": fixture["task"],
                "editable_files": ["engine.py"], "acceptance_tests": ["test_engine.py"],
                "max_attempts": 2,
            })
            broker = ToolBroker(goal, scratch=scratch)
            attempts = []
            for n, candidate in enumerate((fixture["first"], fixture["final"]), start=1):
                if _cancelled(root, job_id):
                    broker.cancel()
                    final_state = "canceled"
                    _note(root, job_id, "canceled", "Stopped cooperatively between sandbox attempts")
                    break
                broker.start_attempt()
                _note(root, job_id, "attempt", f"Reference attempt {n} of 2")
                broker.dispatch({"seq": broker.sequence, "tool": "repo.list", "args": {}})
                broker.dispatch({"seq": broker.sequence, "tool": "repo.read", "args": {"path": "engine.py"}})
                broker.dispatch({"seq": broker.sequence, "tool": "edit.propose", "args": {
                    "edits": [{"path": "engine.py", "content": candidate}],
                }})
                outcome = broker.dispatch({"seq": broker.sequence, "tool": "tests.run", "args": {"suite": "public"}})
                attempts.append({
                    "attempt": n, "passed": outcome["passed"],
                    "tests_run": outcome["tests_run"],
                    "selected_tests_run": outcome["selected_tests_run"],
                    "feedback": outcome["feedback"][-650:],
                    "proposed_sha256": hashlib.sha256(candidate.encode()).hexdigest(),
                })
                _note(root, job_id, "sandbox_test", f"Attempt {n}: {'PASS' if outcome['passed'] else 'FAIL'}; tests={outcome['tests_run']}")
                if outcome["passed"]:
                    final_state = "verified_rehearsal"
                    break
            if final_state == "verified_rehearsal" and (len(attempts) != 2 or attempts[0]["passed"]):
                raise CodingStop("Expected fail-then-pass demonstration did not occur")
            evidence = broker.result()
            if not AuditChain.verify(broker.audit.rows, broker.audit.head) or not evidence["original_unchanged"]:
                raise CodingStop("Audit or original source integrity failed")
            if (project / "engine.py").read_text(encoding="utf-8") != fixture["source"]:
                raise CodingStop("Original fixture was modified")
            result = {"kind": "deterministic_simulation", "attempts": attempts,
                      "audit_sha256": evidence["audit_sha256"], "audit_events": evidence["events"],
                      "original_unchanged": True, "applied_to_owner_repository": False}
    except (OSError, ValueError, RuntimeError, sqlite3.DatabaseError) as exc:
        failure = type(exc).__name__
        final_state = "failed"
    with db(root) as conn:
        conn.execute("BEGIN IMMEDIATE")
        latest = _read(conn, job_id)
        if latest["state"] == "cancel_requested":
            final_state = "canceled"
        conn.execute("UPDATE jobs SET state=?,updated=?,result=?,error=? WHERE id=?",
                     (final_state, int(time.time()), json.dumps(result) if result else None,
                      failure, job_id))
        _event(conn, job_id, "finished", "Rehearsal " + final_state + (": " + failure if failure else ""))
        return _read(conn, job_id)


